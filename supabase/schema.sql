-- ---------- Hàm cho khách: kiểm tra số có được COD không ----------
create or replace function public.cod_allowed(p_phone text) returns boolean
language sql stable security definer set search_path = public as $$
  select not exists (
    select 1 from public.blocked_phones
    where phone = regexp_replace(regexp_replace(coalesce(p_phone,''), '[\s.\-]', '', 'g'), '^\+84', '0')
  );
$$;

-- ---------- Hàm cho khách: đặt hàng ----------
-- Giá, phí ship, tiền cọc đều tính lại trên server, khách không sửa được.
create or replace function public.place_order(
  p_items jsonb, p_method text, p_name text, p_phone text, p_address text, p_city text default '', p_note text default ''
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  s public.shop_settings;
  v_phone text := regexp_replace(regexp_replace(coalesce(p_phone,''), '[\s.\-]', '', 'g'), '^\+84', '0');
  v_items jsonb := '[]'::jsonb;
  v_sub int := 0; v_ship int := 0; v_fee int := 0; v_total int; v_dep int := 0;
  r record; pr public.products; v_qty int; v_code text; i int := 0;
begin
  if p_method not in ('bank','cod') then raise exception 'BAD_METHOD'; end if;
  if v_phone !~ '^0(3|5|7|8|9)[0-9]{8}$' then raise exception 'BAD_PHONE'; end if;
  if length(trim(coalesce(p_name,''))) < 2 then raise exception 'BAD_NAME'; end if;
  if length(trim(coalesce(p_address,''))) < 6 then raise exception 'BAD_ADDRESS'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then raise exception 'EMPTY_CART'; end if;
  if (select count(*) from public.orders where phone = v_phone and created_at > now() - interval '10 minutes') >= 5 then raise exception 'TOO_MANY'; end if;

  for r in select * from jsonb_to_recordset(p_items) as x(id bigint, qty int) loop
    select * into pr from public.products where id = r.id and visible;
    if not found then raise exception 'PRODUCT_NOT_FOUND:%', r.id; end if;
    if not pr.in_stock then raise exception 'OUT_OF_STOCK:%', pr.name; end if;
    v_qty := greatest(1, least(coalesce(r.qty,1), 20));
    v_sub := v_sub + coalesce(pr.sale, pr.price) * v_qty;
    v_items := v_items || jsonb_build_object('id', pr.id, 'name', pr.name, 'brand', pr.brand, 'vol', pr.vol, 'price', coalesce(pr.sale, pr.price), 'qty', v_qty);
  end loop;

  select * into s from public.shop_settings where id = 1;
  if p_method = 'cod' then
    if v_sub > s.cod_max then raise exception 'COD_OVER_MAX'; end if;
    if not public.cod_allowed(v_phone) then raise exception 'COD_BLOCKED'; end if;
    v_ship := s.ship_fee; v_fee := s.cod_fee;
  end if;
  v_total := v_sub + v_ship + v_fee;
  if p_method = 'bank' then v_dep := v_total;
  elsif v_sub >= s.cod_deposit_from then v_dep := (round(v_total * s.cod_deposit_rate / 1000.0) * 1000)::int;
  end if;

  loop
    v_code := 'LUNA' || to_char(now() at time zone 'Asia/Ho_Chi_Minh', 'DDMM') || lpad((floor(random() * 10000))::int::text, 4, '0');
    exit when not exists (select 1 from public.orders where code = v_code);
    i := i + 1; if i > 20 then raise exception 'CODE_FAIL'; end if;
  end loop;

  insert into public.orders (code, status, method, items, subtotal, ship, fee, total, deposit, buyer_name, phone, address, city, note)
  values (v_code, case when p_method = 'bank' or v_dep > 0 then 'cho_thanh_toan' else 'cho_xac_nhan' end, p_method, v_items,
          v_sub, v_ship, v_fee, v_total, v_dep, left(trim(p_name),120), v_phone, left(trim(p_address),300), left(coalesce(p_city,''),80), left(coalesce(p_note,''),300));

  return jsonb_build_object('code', v_code, 'method', p_method, 'subtotal', v_sub, 'ship', v_ship, 'fee', v_fee, 'total', v_total, 'deposit', v_dep, 'items', v_items);
end $$;

revoke all on function public.place_order(jsonb,text,text,text,text,text,text) from public;
grant execute on function public.place_order(jsonb,text,text,text,text,text,text) to anon, authenticated;
grant execute on function public.cod_allowed(text) to anon, authenticated;

