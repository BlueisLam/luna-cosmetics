-- Lịch sử trạng thái đơn (tự ghi mỗi khi đổi trạng thái hoặc nhận tiền)
create table if not exists public.order_events (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  status text not null,
  created_at timestamptz not null default now()
);
create index if not exists order_events_order_idx on public.order_events (order_id, created_at);
alter table public.order_events enable row level security;
drop policy if exists "admin xem lịch sử" on public.order_events;
create policy "admin xem lịch sử" on public.order_events for select using (public.is_admin());

create or replace function public.log_order_event() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    insert into public.order_events (order_id, status) values (new.id, new.status);
  else
    if new.paid and not old.paid then
      insert into public.order_events (order_id, status) values (new.id, 'da_thanh_toan');
    end if;
    if new.status is distinct from old.status then
      insert into public.order_events (order_id, status) values (new.id, new.status);
    end if;
  end if;
  return new;
end $$;
drop trigger if exists orders_log_event on public.orders;
create trigger orders_log_event after insert or update of status, paid on public.orders
for each row execute function public.log_order_event();

-- Đơn đã có từ trước: ghi mốc đặt hàng
insert into public.order_events (order_id, status, created_at)
select o.id, o.status, o.created_at from public.orders o
where not exists (select 1 from public.order_events e where e.order_id = o.id);

-- Khách tra cứu đơn: phải đúng cả mã đơn và số điện thoại đặt hàng.
-- "Bom hàng" hiện với khách là "Đã huỷ".
create or replace function public.track_order(p_code text, p_phone text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  o public.orders;
  v_phone text := regexp_replace(regexp_replace(coalesce(p_phone,''), '[\s.\-]', '', 'g'), '^\+84', '0');
begin
  select * into o from public.orders where code = upper(trim(coalesce(p_code,''))) and phone = v_phone;
  if not found then return null; end if;
  return jsonb_build_object(
    'code', o.code, 'created_at', o.created_at,
    'status', case when o.status = 'bom_hang' then 'da_huy' else o.status end,
    'method', o.method, 'paid', o.paid, 'items', o.items,
    'subtotal', o.subtotal, 'ship', o.ship, 'fee', o.fee, 'total', o.total, 'deposit', o.deposit,
    'buyer_name', o.buyer_name, 'address', o.address, 'city', o.city,
    'carrier', o.carrier, 'tracking_code', o.tracking_code,
    'events', coalesce((select jsonb_agg(jsonb_build_object('status', case when e.status = 'bom_hang' then 'da_huy' else e.status end, 'at', e.created_at) order by e.created_at, e.id)
                        from public.order_events e where e.order_id = o.id), '[]'::jsonb)
  );
end $$;
revoke all on function public.track_order(text,text) from public;
grant execute on function public.track_order(text,text) to anon, authenticated;

