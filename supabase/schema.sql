-- ---------- Admin ----------
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;
drop policy if exists "admin xem chính mình" on public.admins;
create policy "admin xem chính mình" on public.admins for select using (user_id = auth.uid());

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------- Cài đặt shop (1 dòng) ----------
create table if not exists public.shop_settings (
  id int primary key default 1 check (id = 1),
  ship_fee int not null default 30000,
  cod_fee int not null default 15000,
  cod_deposit_from int not null default 1000000,
  cod_deposit_rate numeric(4,3) not null default 0.3 check (cod_deposit_rate between 0 and 1),
  cod_max int not null default 5000000,
  updated_at timestamptz not null default now()
);
insert into public.shop_settings (id) values (1) on conflict (id) do nothing;
alter table public.shop_settings enable row level security;
drop policy if exists "ai cũng xem" on public.shop_settings;
create policy "ai cũng xem" on public.shop_settings for select using (true);
drop policy if exists "admin sửa" on public.shop_settings;
create policy "admin sửa" on public.shop_settings for update using (public.is_admin()) with check (public.is_admin());

